/* Reuse the real StackDock artwork and starter layout from the current checkout.
 * Usage from the repo root: node native-prototype/tools/sync-assets.cjs
 * Requires Inkscape in PATH. Generated assets are checked in. */
const fs = require("node:fs"), vm = require("node:vm"), path = require("node:path");
const { execFileSync } = require("node:child_process");
const root=path.resolve(__dirname,"../.."), assets=path.join(__dirname,"../assets");
const html=fs.readFileSync(path.join(root,"index.html"),"utf8");
const source=html.slice(html.indexOf("let folderGradientId=0"),html.indexOf("let state=fresh();"));
if(!source.startsWith("let folderGradientId") || !source.includes("function fresh()")) throw Error("Could not find StackDock's frontend definitions");
const data=vm.runInNewContext(source+`
(() => {
 const layout=fresh();
 layout.folders.forEach((f,i)=>{f.id="stackdock-starter-"+i});
 const icons=Object.fromEntries(Object.entries({...FOLDER_ICONS,...APP_ICONS}).map(([k,x])=>[k,typeof x.svg==="function"?x.svg():x.svg]));
 return {icons,layout};
})()`,{}, {timeout:1000});
const tmp=fs.mkdtempSync(path.join(require("node:os").tmpdir(),"stackdock-icons-"));
try{
 fs.mkdirSync(assets,{recursive:true});
 for(const [key,svg] of Object.entries(data.icons)){
  if(!/^[a-z0-9-]+$/.test(key)) throw Error("Invalid SVG key");
  const file=path.join(tmp,key+".svg");
  fs.writeFileSync(file,svg);
  execFileSync("inkscape",[file,"--export-width=128","--export-height=128","--export-filename="+path.join(assets,key+".png")],{stdio:"ignore"});
 }
 fs.writeFileSync(path.join(assets,"starter.json"),JSON.stringify({format:"stack-dock-layout",version:1,layout:data.layout},null,2)+"\n");
 const names=Object.keys(data.icons);
 fs.writeFileSync(path.join(assets,"icons.rs"),'// Generated by tools/sync-assets.cjs.\n&[\n'+names.map(k=>'    ("'+k+'", include_bytes!("'+k+'.png")),').join("\n")+'\n]\n');
}finally{fs.rmSync(tmp,{recursive:true,force:true})}
